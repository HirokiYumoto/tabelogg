    protected $signature = 'ramen:seed {--count=100000}';
    protected $description = 'ラーメン屋のテストデータを一括登録';

    public function handle(): int
    {
        $count = (int) $this->option('count');
        $this->info("ラーメン屋 {$count} 件の登録を開始します...");

        // 1. ユーザー取得/作成
        $user = User::firstOrCreate(
            ['email' => 'test10@aidma-hd.jp'],
            [
                'name' => 'テストオーナー10',
                'password' => Hash::make('11111111'),
                'role_id' => 2,
                'email_verified_at' => now(),
            ]
        );
        if ($user->role_id !== 2) {
            $user->update(['role_id' => 2]);
        }

        // 2. 市区町村ロード
        $cities = City::all(['id', 'name', 'prefecture_id'])->toArray();
        if (empty($cities)) {
            $this->error('市区町村データがありません。先に cities:import を実行してください。');
            return 1;
        }
        $this->info('市区町村: ' . count($cities) . ' 件ロード済み');

        // 3. 郵便番号ロード
        $postalByCity = [];
        try {
            $postalByCity = DB::table('postal_codes')
                ->selectRaw('city_id, MIN(postal_code) as postal_code')
                ->groupBy('city_id')
                ->pluck('postal_code', 'city_id')
                ->toArray();
        } catch (\Exception $e) {
            $this->warn('postal_codes テーブルが見つかりません。郵便番号は空で登録します。');
        }

        // 4. データプール
        $namePrefixes = $this->getNamePrefixes();
        $nameWords = $this->getNameWords();
        $nameSuffixes = $this->getNameSuffixes();
        $descriptions = $this->getDescriptions();
        $menus = $this->getMenus();
        $seatPatterns = $this->getSeatPatterns();
        $timePatterns = $this->getTimePatterns();
        $prefCoords = $this->getPrefectureCoords();
        $stationsByPref = $this->getStationsByPrefecture();

        // 5. 一括登録
        $chunkSize = 2000;
        $bar = $this->output->createProgressBar($count);
        $bar->start();

        for ($offset = 0; $offset < $count; $offset += $chunkSize) {
            $batchSize = min($chunkSize, $count - $offset);
            $restaurantRows = [];
            $batchMeta = [];
            $now = now()->toDateTimeString();

            for ($i = 0; $i < $batchSize; $i++) {
                $city = $cities[array_rand($cities)];
                $prefId = $city['prefecture_id'];

                // 店舗名
                $name = $namePrefixes[array_rand($namePrefixes)] . ' '
                    . $nameWords[array_rand($nameWords)]
                    . $nameWords[array_rand($nameWords)]
                    . $nameSuffixes[array_rand($nameSuffixes)];

                // 最寄り駅
                $stations = $stationsByPref[$prefId] ?? [mb_substr($city['name'], 0, -1) . '駅'];
                $station = $stations[array_rand($stations)];

                // 住所
                $addr = rand(1, 9) . '-' . rand(1, 30) . '-' . rand(1, 20);

                // 郵便番号
                $postal = $postalByCity[$city['id']] ?? null;

                // 座標
                $base = $prefCoords[$prefId] ?? [35.68, 139.69];
                $lat = round($base[0] + (rand(-500, 500) / 10000), 6);
                $lng = round($base[1] + (rand(-500, 500) / 10000), 6);

                // 座席パターン
                $pattern = $seatPatterns[array_rand($seatPatterns)];
                $resolvedSeats = [];
                $maxParty = 0;
                foreach ($pattern as $seat) {
                    $cap = rand($seat['cap_min'], $seat['cap_max']);
                    $resolvedSeats[] = [
                        'type' => $seat['type'],
                        'seats_per_unit' => $seat['spu'],
                        'capacity' => $cap,
                    ];
                    $maxParty += $seat['spu'] * $cap;
                }

                $restaurantRows[] = [
                    'user_id' => $user->id,
                    'city_id' => $city['id'],
                    'name' => $name,
                    'description' => $descriptions[array_rand($descriptions)],
                    'menu_info' => $menus[array_rand($menus)],
                    'nearest_station' => $station,
                    'address' => $addr,
                    'postal_code' => $postal,
                    'latitude' => $lat,
                    'longitude' => $lng,
                    'max_party_size' => $maxParty,
                    'created_at' => $now,
                    'updated_at' => $now,
                ];

                $batchMeta[] = [
                    'seats' => $resolvedSeats,
                    'times' => $timePatterns[array_rand($timePatterns)],
                ];
            }

            DB::beginTransaction();
            try {
                DB::table('restaurants')->insert($restaurantRows);
                $firstId = (int) DB::getPdo()->lastInsertId();

                $seatRows = [];
                $timeRows = [];
                $imageRows = [];

                for ($i = 0; $i < $batchSize; $i++) {
                    $rid = $firstId + $i;

                    foreach ($batchMeta[$i]['seats'] as $seat) {
                        $seatName = $seat['type'] === 'counter'
                            ? "カウンター（{$seat['capacity']}席）"
                            : "{$seat['seats_per_unit']}名テーブル（{$seat['capacity']}卓）";
                        $seatRows[] = [
                            'restaurant_id' => $rid,
                            'name' => $seatName,
                            'type' => $seat['type'],
                            'seats_per_unit' => $seat['seats_per_unit'],
                            'capacity' => $seat['capacity'],
                            'created_at' => $now,
                            'updated_at' => $now,
                        ];
                    }

                    foreach ($batchMeta[$i]['times'] as $tp) {
                        $timeRows[] = [
                            'restaurant_id' => $rid,
                            'day_of_week' => 7,
                            'start_time' => $tp['start'],
                            'end_time' => $tp['end'],
                            'stay_minutes' => $tp['stay'],
                            'created_at' => $now,
                            'updated_at' => $now,
                        ];
                    }

                    $imageRows[] = [
                        'restaurant_id' => $rid,
                        'image_path' => 'restaurant_images/ラーメン.jpg',
                        'created_at' => $now,
                        'updated_at' => $now,
                    ];
                }

                foreach (array_chunk($seatRows, 5000) as $chunk) {
                    DB::table('restaurant_seat_types')->insert($chunk);
                }
                foreach (array_chunk($timeRows, 5000) as $chunk) {
                    DB::table('restaurant_time_settings')->insert($chunk);
                }
                DB::table('restaurant_images')->insert($imageRows);

                DB::commit();
            } catch (\Exception $e) {
                DB::rollBack();
                $this->newLine();
                $this->error("チャンク {$offset} でエラー: " . $e->getMessage());
                return 1;
            }

            $bar->advance($batchSize);
        }

        $bar->finish();
        $this->newLine(2);
        $this->info("完了: {$count} 件のラーメン屋を登録しました（オーナー: {$user->email}）");
        $this->warn('Meilisearch再インデックスを実行してください:');
        $this->line('  php artisan scout:import "App\\Models\\Restaurant"');

        return 0;
    }

